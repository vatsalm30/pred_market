import { NextRequest, NextResponse } from "next/server";

export const dynamic = "force-dynamic";

// Daily news stories are now written by the content job on GCP (gcp/pipeline/generate_content.py),
// which posts them to /api/content. This route stays so the old AWS schedule doesn't error.
export async function GET(req: NextRequest): Promise<NextResponse> {
  if (req.headers.get("authorization") !== `Bearer ${process.env.CRON_SECRET}`) {
    return NextResponse.json({ error: "Forbidden" }, { status: 403 });
  }
  return NextResponse.json({ ok: true, note: "news stories are generated by the GCP content job" });
}
